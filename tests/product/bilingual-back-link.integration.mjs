import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { listToolDefinitions } from '../../src/product/tool-definitions.js';

const currentDir = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(currentDir, '../..');

/**
 * A real, user-reported bug: every single tool page's "back to all tools"
 * link was permanently stuck in Arabic ("كل الأدوات"), even when the page
 * was actively viewed in English -- confirmed directly from a screenshot of
 * the English-mode video-audio-remover page showing "← كل الأدوات" above
 * fully English content ("Remove Audio from Video", "Choose a video").
 *
 * Root cause: the back-link span used `id="back-label"` with a single
 * hardcoded Arabic string, while `tool-page.js`'s `updateCopy()` function
 * only toggles elements carrying a `data-copy` attribute -- confirmed
 * directly that `tool-page.js` has zero code referencing `back-label` at
 * all, so nothing ever updated it on language switch. Notably, the
 * generator script's OWN comment ("Title / description / note / back use
 * data-copy spans in HTML -- toggle only") already documented the intended
 * design; the template just didn't implement it for this one element.
 *
 * Fixed by switching the back-link to the same `data-copy="ar"`/
 * `data-copy="en"` bilingual-span pattern already used correctly
 * everywhere else on the site (including the exact same file's other
 * catalogue-page template, and the site-wide header/brand markup).
 */

{
    const allTools = listToolDefinitions();
    const interactiveToolIds = new Set(allTools.filter((tool) => tool.interactive).map((tool) => tool.id));
    const missingBilingualBackLink = [];
    const staleIdPattern = [];

    for (const tool of allTools) {
        if (interactiveToolIds.has(tool.id)) continue; // hand-authored pages, not generated by this template

        // eslint-disable-next-line no-await-in-loop -- keeps a failure attributable to one exact page
        const html = await readFile(path.join(projectRoot, 'tools', tool.id, 'index.html'), 'utf8');

        if (html.includes('id="back-label"')) {
            staleIdPattern.push(tool.id);
        }
        if (!/<a class="product-back"[^>]*><span aria-hidden="true">←<\/span><span data-copy="ar">كل الأدوات<\/span><span data-copy="en">All tools<\/span><\/a>/.test(html)) {
            missingBilingualBackLink.push(tool.id);
        }
    }

    assert.deepEqual(staleIdPattern, [], `${staleIdPattern.length} tool page(s) still use the old, never-translated id="back-label" pattern: ${staleIdPattern.slice(0, 5).join(', ')}`);
    assert.deepEqual(missingBilingualBackLink, [], `${missingBilingualBackLink.length} tool page(s) are missing the correct bilingual back-link markup: ${missingBilingualBackLink.slice(0, 5).join(', ')}`);
}

console.log('Bilingual back-link verified across every non-interactive tool page: no stale id="back-label" pattern remains, and every page has the correct data-copy bilingual markup.');

